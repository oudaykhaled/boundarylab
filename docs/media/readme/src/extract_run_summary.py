#!/usr/bin/env python3
"""Extract README display data from retained public AOSP receipts, using stdlib only.

Run from any directory: python3 docs/media/readme/src/extract_run_summary.py
Use --check to compare without modifying the canonical output. No builds, tests,
network calls, cloud operations or current timestamps are generated by this tool.

Schema: each display metric has value, unit, scope and sources. Each source has a
repository-relative path plus an RFC 6901 JSON pointer or inclusive one-based
line range. sourceFiles binds every selected source to its SHA-256. Chart labels
and scopes are editorial descriptions; recorded values come from cited fields.
The four check layers overlap and MUST NOT be summed. Timeline timestamps show
this single development run, including incremental builds, not performance.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


CUSTOM = "docs/evidence/aosp/custom-20261030"
BASELINE = "docs/evidence/P02/r5-source-baseline"
HOST = "docs/evidence/aosp/attempt-20261030"
TEARDOWN = "docs/evidence/aosp/teardown-20261030"
OUTPUT = "docs/media/readme/data/run-summary.json"


class Receipts:
    """Read only explicit repository receipts and retain their content identities."""

    def __init__(self, root: Path) -> None:
        self.root = root
        self.files: dict[str, str] = {}

    def text(self, path: str) -> str:
        resolved = (self.root / path).resolve()
        if not resolved.is_relative_to(self.root):
            raise ValueError(f"Source is outside repository: {path}")
        raw = resolved.read_bytes()
        self.files[path] = hashlib.sha256(raw).hexdigest()
        return raw.decode("utf-8")

    def read(self, path: str) -> Any:
        return json.loads(self.text(path))

    def at(self, path: str, pointer: str) -> Any:
        value = self.read(path)
        for part in pointer.lstrip("/").split("/") if pointer else []:
            key = part.replace("~1", "/").replace("~0", "~")
            value = value[int(key)] if isinstance(value, list) else value[key]
        return value

    def metric(self, path: str, pointer: str, unit: str, scope: str) -> dict[str, Any]:
        return {
            "value": self.at(path, pointer),
            "unit": unit,
            "scope": scope,
            "sources": [{"path": path, "pointer": pointer}],
        }

    def derived(
        self, value: Any, unit: str, scope: str, sources: list[dict[str, Any]],
        derivation: str,
    ) -> dict[str, Any]:
        for source in sources:
            if "pointer" in source:
                self.at(source["path"], source["pointer"])
            else:
                lines = self.text(source["path"]).splitlines()
                start, end = source["lines"]
                if not 1 <= start <= end <= len(lines):
                    raise ValueError(f"Invalid source lines: {source}")
        return {
            "value": value, "unit": unit, "scope": scope,
            "sources": sources, "derivation": derivation,
        }

    def line_source(self, path: str, prefix: str) -> dict[str, Any]:
        matches = [i for i, line in enumerate(self.text(path).splitlines(), 1)
                   if line.startswith(prefix)]
        if len(matches) != 1:
            raise ValueError(f"Expected one source line for {prefix!r} in {path}")
        return {"path": path, "lines": [matches[0], matches[0]]}


def ref(path: str, pointer: str) -> dict[str, str]:
    return {"path": path, "pointer": pointer}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[4])
    parser.add_argument("--check", action="store_true", help="Check deterministic output without writing")
    args = parser.parse_args()
    root = args.root.resolve()
    r = Receipts(root)
    actual = f"{CUSTOM}/actual-results.json"
    run = f"{CUSTOM}/runtime/r6/run-result.json"
    cost = f"{TEARDOWN}/cost-estimate.json"
    deletion = f"{TEARDOWN}/teardown.json"
    host = f"{HOST}/host-kvm.json"
    controls = f"{HOST}/cloud-controls.json"
    baseline_build = f"{BASELINE}/build-result.json"
    baseline_boot = f"{BASELINE}/boot-run-result.json"
    baseline_checks = f"{BASELINE}/boot/checks.json"
    smoke = f"{CUSTOM}/runtime/r6/smoke/checks.json"
    native = f"{CUSTOM}/runtime/r6/native61.jsonl"

    operator_rows = r.at(run, "/checks")
    harness_rows = r.at(smoke, "/checks")
    baseline_rows = r.at(baseline_checks, "")
    native_rows = [json.loads(line) for line in r.text(native).splitlines() if line]
    native_cases = [row for row in native_rows if "case" in row]
    if len({row["case"] for row in native_cases}) != len(native_cases):
        raise ValueError("Native assertion names are not unique")
    if [row for row in native_rows if "summary" in row] != [{"summary": "PASS", "checks": 61}]:
        raise ValueError("Native summary differs from retained PASS/61 receipt")
    for rows, expected in [(operator_rows, 34), (harness_rows, 236),
                           (native_cases, 61), (baseline_rows, 18)]:
        if len(rows) != expected or not all(row["passed"] is True for row in rows):
            raise ValueError(f"Unexpected count or outcome for retained {expected}-row layer")

    def count_metric(value: int, path: str, pointer: str, scope: str, operation: str) -> dict[str, Any]:
        return r.derived(value, "count", scope, [ref(path, pointer)], operation)

    def native_count(value: int, scope: str, operation: str) -> dict[str, Any]:
        return r.derived(value, "count", scope, [{"path": native, "lines": [1, len(native_rows)]}], operation)

    counts = {
        "baselineChecks": count_metric(len(baseline_rows), baseline_checks, "",
            "Unchanged Android 16 baseline; separate from custom-image proof.", "len(root array)"),
        "baselinePassed": count_metric(sum(x["passed"] for x in baseline_rows), baseline_checks, "",
            "Unchanged baseline checks with passed=true.", "count(root rows where passed is true)"),
        "operatorChecks": count_metric(len(operator_rows), run, "/checks",
            "Final r6 operator checks, including harness/native summaries; overlaps other layers.", "len(checks)"),
        "operatorPassed": count_metric(sum(x["passed"] for x in operator_rows), run, "/checks",
            "Final r6 operator checks with passed=true.", "count(checks where passed is true)"),
        "harnessObservations": count_metric(len(harness_rows), smoke, "/checks",
            "Final r6 observations include repeated case/identity names; not 236 unique tests.", "len(checks)"),
        "harnessPassed": count_metric(sum(x["passed"] for x in harness_rows), smoke, "/checks",
            "Final r6 harness observations with passed=true.", "count(checks where passed is true)"),
        "nativeAssertions": native_count(len(native_cases),
            "Unique native assertion cases; executed once under su, a permissive domain.",
            "count(distinct case names); summary row excluded"),
        "nativePassed": native_count(sum(x["passed"] for x in native_cases),
            "Unique native cases with passed=true; not proof that su is enforcing.",
            "count(case rows where passed is true); summary row excluded"),
        "failedRuntimeAttempts": count_metric(len(r.at(actual, "/preserved_failed_attempts")), actual,
            "/preserved_failed_attempts", "r1-r5 are retained failures, followed by passing r6.",
            "len(preserved_failed_attempts)"),
    }

    host_data = {
        "system": r.metric(host, "/system", "name", "Recorded host preflight, not Android guest kernel."),
        "architecture": r.metric(host, "/architecture", "name", "Recorded Linux host architecture."),
        "kernel": r.metric(host, "/kernel", "version", "Recorded Linux host kernel."),
        "machineType": r.metric(controls, "/machine_type", "name", "Applied Google Cloud VM machine type."),
        "cpuCount": r.metric(host, "/cpus", "logical CPU", "Logical CPUs observed by host preflight."),
        "memoryKiB": r.metric(host, "/memoryKiB", "KiB", "Memory reported to the Linux host; not nominal SKU RAM."),
        "memoryGiB": r.derived(round(r.at(host, "/memoryKiB") / 1024**2, 4), "GiB",
            "Observed Linux host memory converted from KiB; not nominal SKU RAM.",
            [ref(host, "/memoryKiB")], "round(memoryKiB / 1024**2, 4)"),
        "kvmApi": r.metric(host, "/kvmApi", "API version", "KVM API ioctl succeeded in host preflight."),
        "transientKvmVmCreatedAndClosed": r.metric(host, "/transientVmCreatedAndClosed", "boolean",
            "KVM preflight created/closed a transient VM; guest boot is established separately."),
        "nestedVirtualization": r.metric(controls, "/nested_virtualization", "boolean", "Applied cloud VM control."),
    }
    identity = {
        "aospTag": r.metric(baseline_build, "/source_manifest", "tag", "Pinned Android source baseline, then same target with overlay."),
        "target": r.metric(baseline_build, "/target", "name", "Actual source build target."),
        "sourceCommit": r.metric(run, "/source_commit", "git SHA", "BoundaryLab source revision used by final r6 proof."),
        "globalSelinuxBefore": r.metric(actual, "/policy/guest_global_before", "mode", "Guest global state before final smoke."),
        "globalSelinuxAfter": r.metric(actual, "/policy/guest_global_after", "mode", "Guest global state after final smoke."),
        "nonpermissiveBoundaryLabDomains": r.metric(actual, "/policy/boundarylab_domains_checked_nonpermissive", "domain list",
            "Domains checked against the loaded guest policy, not every Android domain."),
        "nativeExecutionIdentity": r.metric(actual, "/native_assertions/execution_identity", "identity",
            "Native assertion identity must remain distinct from authorized Binder probe identity."),
    }

    def phase(identifier: str, label: str, path: str, start: str | None,
              end: str, scope: str, exit_code: bool = False) -> dict[str, Any]:
        passed = (r.derived(r.at(path, "/exit_code") == 0, "boolean", scope,
                   [ref(path, "/exit_code")], "exit_code == 0") if exit_code
                  else r.metric(path, "/passed", "boolean", scope))
        return {
            "id": identifier, "label": label, "scope": scope,
            "startedUtc": r.metric(path, start, "UTC timestamp", scope) if start else None,
            "endedUtc": r.metric(path, end, "UTC timestamp", scope), "passed": passed,
        }

    timeline = [
        phase("baseline-build", "Unchanged AOSP source build", baseline_build,
              "/started_utc", "/ended_utc", "One development build; elapsed time is not a benchmark.", True),
        phase("baseline-boot", "Unchanged source baseline boot and cleanup", baseline_boot,
              "/window/started_utc", "/ended_utc", "Unchanged baseline before BoundaryLab overlay."),
        phase("native-r5", "Final incremental native build", f"{CUSTOM}/build/native-r5/build-result.json",
              "/started_utc", "/ended_utc", "Final incremental native compilation; not clean-build performance.", True),
        phase("image-r4", "Final incremental image build", f"{CUSTOM}/build/image-r4/build-result.json",
              "/started_utc", "/ended_utc", "Final incremental image package; compilation is not runtime assertion execution.", True),
    ]
    runtime_phase = phase("runtime-r6", "Custom image boot, combined proof and cleanup", run,
        None, "/ended_utc", "Minimum combined runtime proof; no performance, soak or fresh reproduction campaign.")
    runtime_phase["startedUtc"] = r.metric(f"{CUSTOM}/runtime/r6/run-window.json", "/started_utc", "UTC timestamp", runtime_phase["scope"])
    timeline.append(runtime_phase)
    export = f"{CUSTOM}/archives/r6-local-verification.json"
    timeline.append({
        "id": "export-verified", "label": "Final evidence archive verified locally",
        "scope": "Local hash verification, not independent execution authenticity.",
        "startedUtc": None,
        "endedUtc": r.metric(export, "/verified_utc", "UTC timestamp", "Verified after export, before deletion."),
        "passed": r.metric(export, "/verified", "boolean", "Local export integrity verification."),
    })
    for identifier, label, pointer in [
        ("charged-resources-deleted", "VM and both disks verified absent", "/charged_resources_absent_since_utc"),
        ("teardown-verified", "Attempt teardown verified", "/verified_utc"),
    ]:
        checks = ["/instance_absent", "/both_disks_absent"]
        if identifier == "teardown-verified":
            checks += ["/deadline_task_deleted", "/deadline_queue_deleted",
                       "/deadline_iam_binding_role_service_account_deleted",
                       "/attempt_firewall_subnet_network_deleted",
                       "/evidence_verified_before_deletion"]
        confirmed = all(r.at(deletion, key) is True for key in checks)
        lists_empty = all(not values for values in r.at(deletion, "/final_resource_lists").values())
        timeline.append({
            "id": identifier, "label": label, "scope": "Operator-recorded provider checks; settled invoice not available.",
            "startedUtc": None,
            "endedUtc": r.metric(deletion, pointer, "UTC timestamp", "Actual retained teardown timestamp."),
            "passed": r.derived(confirmed and lists_empty, "boolean",
                "Conjunction of cited absence/deletion fields and empty final provider resource lists.",
                [ref(deletion, key) for key in checks] + [ref(deletion, "/final_resource_lists")],
                "all(cited boolean fields are true) and all(final_resource_lists values are empty)"),
        })

    failure_reasons = {
        1: "Shell could not hash a protected system_ext service binary; functional harness not reached.",
        2: "Native test file had matching hash but mode 0644 instead of executable 0755; functional harness not reached.",
        3: "Probe could not read selinuxfs/enforce; global_enforcing observation failed after authorized-domain entry.",
        4: "Raw-FD classification assertion failed; old detail label does not establish the historical numeric Binder status.",
        5: "Denied fixture observed Android UID 9999 against old 65534 expectation; stopped before typed DENIED call.",
        6: "Complete minimum combined proof passed; earlier failed attempts remain failures.",
    }
    attempts = []
    for number in range(1, 7):
        path = f"{CUSTOM}/runtime/r{number}/run-result.json"
        value = r.read(path)
        if value["passed"] is not (number == 6) or value["cleanup_verified"] is not True:
            raise ValueError(f"Runtime r{number} outcome changed")
        started = datetime.fromtimestamp(value["started_epoch"], timezone.utc).isoformat(timespec="microseconds")
        reason_source = r.line_source(f"{CUSTOM}/README.md", f"| r{number} |")
        attempts.append({
            "id": f"r{number}",
            "passed": r.metric(path, "/passed", "boolean", "Whole attempt result; passing subset does not override failure."),
            "startedUtc": r.derived(started, "UTC timestamp", "Operator recorded runtime start.",
                [ref(path, "/started_epoch")], "datetime.fromtimestamp(started_epoch, UTC).isoformat(timespec='microseconds')"),
            "endedUtc": r.metric(path, "/ended_utc", "UTC timestamp", "Operator recorded runtime end."),
            "reason": r.derived(failure_reasons[number], "description", "Editorial diagnosis tied to retained attempt table and aggregate.",
                [reason_source, ref(path, "/error"), ref(path, "/passed")], "Concise description of cited runtime-attempt row; no failure reclassified."),
            "cleanupVerified": r.metric(path, "/cleanup_verified", "boolean", "Attempt guest/build process cleanup; cloud teardown is separate."),
        })

    cost_data = {
        "infrastructureEstimateUsd": r.metric(cost, "/infrastructure_subtotal_estimate_usd", "USD",
            "VM, SSD/standard disk and IPv4 through verified deletion; estimate, not settled invoice."),
        "reservedEstimateUsd": r.metric(cost, "/allin_projection_with_2usd_egress_and_40pct_taxfx_reserve_usd", "USD",
            "Same infrastructure plus USD 2 egress allowance and 40% tax/FX reserve; estimate, not actual spend."),
        "budgetUsd": r.metric(cost, "/limit_usd", "USD", "Authorized total infrastructure cap for this bounded attempt."),
        "settledInvoiceAvailable": r.metric(cost, "/settled_invoice_available", "boolean", "No provider invoice total is asserted."),
        "chargedHoursEstimate": r.metric(cost, "/accrued_running_hours_estimate", "hours", "Cost clock stops at verified charged-resource deletion."),
        "estimateEndUtc": r.metric(cost, "/estimate_end_utc", "UTC timestamp", "Estimate endpoint, not a future live accrual clock."),
    }
    teardown_data = {
        "chargedResourcesAbsentSinceUtc": r.metric(deletion, "/charged_resources_absent_since_utc", "UTC timestamp", "VM and both disks verified absent."),
        "verifiedUtc": r.metric(deletion, "/verified_utc", "UTC timestamp", "Final attempt teardown provider checks completed."),
        "instanceAbsent": r.metric(deletion, "/instance_absent", "boolean", "Attempt-owned VM only."),
        "bothDisksAbsent": r.metric(deletion, "/both_disks_absent", "boolean", "Attempt-owned boot and workspace disks."),
        "finalResourceLists": r.metric(deletion, "/final_resource_lists", "resource lists", "All listed attempt-scoped provider responses are empty."),
        "evidenceVerifiedBeforeDeletion": r.metric(deletion, "/evidence_verified_before_deletion", "boolean", "Export and local verification preceded deletion."),
    }
    result = {
        "schemaVersion": 1,
        "title": "BoundaryLab: actual Android 16 source build and custom-image proof on Linux/KVM",
        "metricSchema": "Each metric has value, unit, scope, sources (repository path + RFC6901 pointer or inclusive one-based lines); derived metrics state the derivation.",
        "scope": "Display dataset derived offline from retained public receipts. No new build, device test, cloud action or current timestamp.",
        "caveats": [
            "Counts are separate overlapping evidence layers; never sum them into unique tests.",
            "236 harness observations include repeated case names. 61 native case names are unique and exclude the summary row.",
            "Native assertions ran under su, which is permissive; the three BoundaryLab domains were checked nonpermissive in loaded policy.",
            "Timeline includes incremental builds and development fixes; it is not a performance comparison.",
            "Actual virtual Android lock-screen PNGs establish visual boot context; service semantics are supported by command receipts.",
            "Compatibility evolution, old consumer, performance, soak and fresh final reproduction remain outside this proof.",
            "Local hashes establish retained-byte integrity, not independent execution attestation.",
            "All costs are estimates. The reserved projection is not a settled bill or additional actual spend.",
        ],
        "host": host_data, "identity": identity, "counts": counts, "timeline": timeline,
        "runtimeAttempts": attempts, "cost": cost_data, "teardown": teardown_data,
        "sourceFiles": [{"path": path, "sha256": digest} for path, digest in sorted(r.files.items())],
    }
    encoded = json.dumps(result, ensure_ascii=False, indent=2) + "\n"
    # Dataset uses selected fields, never raw provider/SSH metadata or private paths.
    if re.search(r"[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}|/Users/|BEGIN .*PRIVATE KEY|boundarylab-aosp-20261030|gserviceaccount", encoded, re.I):
        raise ValueError("Privacy filter rejected selected display data")
    destination = root / OUTPUT
    if args.check:
        if not destination.exists() or destination.read_text(encoding="utf-8") != encoded:
            parser.exit(1, "Run-summary differs from deterministic retained-receipt extraction.\n")
        print(f"Verified {OUTPUT}: {len(r.files)} source files, separate 18/34/236/61 evidence layers.")
    else:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(encoded, encoding="utf-8")
        print(f"Wrote {OUTPUT}: {len(r.files)} cited source files, {len(encoded.encode('utf-8'))} bytes.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
