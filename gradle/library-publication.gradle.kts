import org.gradle.api.publish.PublishingExtension
import org.gradle.api.publish.maven.MavenPublication
import org.gradle.api.tasks.bundling.AbstractArchiveTask
import org.gradle.jvm.tasks.Jar

// Deliberately folder-only: these coordinates are not a public-registry availability claim.
val repositoryUri = rootProject.uri(providers.gradleProperty("boundarylabRepository")
    .getOrElse(rootProject.layout.buildDirectory.dir("local-maven").get().asFile.absolutePath))
require(repositoryUri.scheme == "file") { "boundarylabRepository must identify a local folder (file: URI or path)" }

val apiDocsJar = tasks.register<Jar>("apiDocsJar") {
    archiveClassifier.set("javadoc")
    // Kotlin API reference generated by Dokka; do not publish an empty Java-only Javadoc archive.
    from(tasks.named("dokkaGeneratePublicationHtml"))
}

configure<PublishingExtension> {
    repositories.maven {
        name = "BoundaryLabLocal"
        url = repositoryUri
    }
    publications.withType<MavenPublication>().configureEach {
        artifact(apiDocsJar)
        pom {
            url.set("https://github.com/oudaykhaled/boundarylab")
            licenses {
                license {
                    name.set("Apache License, Version 2.0")
                    url.set("https://www.apache.org/licenses/LICENSE-2.0.txt")
                    distribution.set("repo")
                }
            }
            scm {
                url.set("https://github.com/oudaykhaled/boundarylab")
                connection.set("scm:git:https://github.com/oudaykhaled/boundarylab.git")
            }
        }
    }
}

tasks.withType<AbstractArchiveTask>().configureEach {
    isPreserveFileTimestamps = false
    isReproducibleFileOrder = true
}
tasks.withType<Jar>().configureEach {
    from(rootProject.file("LICENSE")) { into("META-INF") }
}
